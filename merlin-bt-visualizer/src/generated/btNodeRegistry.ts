import { EditorNodeKind, EditorNodeSource, EditorUiType } from '../types/editor';

export type BtPortDirection = 'input' | 'output' | 'inout';
export type BtBindingMode = 'literal' | 'blackboard' | 'both';

export interface BtPortSchema {
  name: string;
  labelZh: string;
  direction: BtPortDirection;
  valueType: string;
  descriptionZh: string;
  defaultValue?: string;
  bindingMode?: BtBindingMode;
}

export interface BtNodeRegistryEntry {
  id: string;
  tagName: string;
  source: EditorNodeSource;
  group: string;
  category: EditorNodeKind;
  uiType: EditorUiType;
  labelZh: string;
  descriptionZh: string;
  switchGroup?: string;
  childPolicy: {
    min: number;
    max: number | null;
  };
  defaultAttributes: Record<string, string>;
  portSchemas: BtPortSchema[];
  keywordsZh: string[];
  keywordsEn: string[];
}

