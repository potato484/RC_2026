import { EditorNodeKind, EditorNodeSource, EditorUiType } from '../types/editor';

export type BtPortDirection = 'input' | 'output' | 'inout';
export type BtBindingMode = 'literal' | 'blackboard' | 'both';

export interface BtPortSchema {
  name: string;
  labelZh: string;
  direction: BtPortDirection;
  valueType: string;
  descriptionZh: string;
  defaultValue?: string;
  bindingMode?: BtBindingMode;
}

export interface BtNodeRegistryEntry {
  id: string;
  tagName: string;
  source: EditorNodeSource;
  group: string;
  category: EditorNodeKind;
  uiType: EditorUiType;
  labelZh: string;
  descriptionZh: string;
  childPolicy: {
    min: number;
    max: number | null;
  };
  defaultAttributes: Record<string, string>;
  portSchemas: BtPortSchema[];
  keywordsZh: string[];
  keywordsEn: string[];
}

const createSwitchNodes = (): BtNodeRegistryEntry[] =>
  (['2', '3', '4', '5', '6'] as const).map<BtNodeRegistryEntry>((count) => ({
    id: `Switch${count}`,
    tagName: `Switch${count}`,
    source: 'official',
    group: '官方控制节点',
    category: 'control',
    uiType: 'control',
    labelZh: `多路切换节点（${count} 路）`,
    descriptionZh: '看一个判定值，命中哪一路就走哪一路。',
    childPolicy: { min: Number(count), max: Number(count) + 1 },
    defaultAttributes: Object.fromEntries([
      ['variable', ''],
      ...Array.from({ length: Number(count) }, (_, index) => [`case_${index + 1}`, '']),
    ]) as Record<string, string>,
    portSchemas: [
      {
        name: 'variable',
        labelZh: '判定变量',
        direction: 'input',
        valueType: 'string',
        descriptionZh: '用于选择分支的变量或黑板键。',
        bindingMode: 'both',
      },
      ...Array.from(
        { length: Number(count) },
        (_, index): BtPortSchema => ({
          name: `case_${index + 1}`,
          labelZh: `条件 ${index + 1}`,
          direction: 'input',
          valueType: 'string',
          descriptionZh: '与判定变量进行匹配的条件值。',
          bindingMode: 'literal',
        })
      ),
    ],
    keywordsZh: ['切换', '多路分支'],
    keywordsEn: [`Switch${count}`],
  }));

