const dictionaries: Record<AppLocale, MessageDict> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function t(locale: AppLocale, key: string, params?: Record<string, string | number>): string {
  const template = dictionaries[locale][key] ?? dictionaries['zh-CN'][key] ?? key;
  if (!params) {
    return template;
  }

  return Object.entries(params).reduce((result, [paramKey, value]) => {
    return result.split(`{${paramKey}}`).join(String(value));
  }, template);
}
